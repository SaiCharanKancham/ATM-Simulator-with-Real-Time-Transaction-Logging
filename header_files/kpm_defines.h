
/*
 * File: kpm_defines.h
 * Description: Defines GPIO pin positions for 4x4 matrix keypad interfacing.
 */

/* Prevent multiple inclusion of this header file. */
#ifndef KPM_DEFINES_H
#define KPM_DEFINES_H

/* Keypad row pin definitions (Port 1). */
#define ROW0 16    // P1.16
#define ROW1 17    // P1.17
#define ROW2 18    // P1.18
#define ROW3 19    // P1.19

/* Keypad column pin definitions (Port 1). */
#define COL0 20    // P1.20
#define COL1 21    // P1.21
#define COL2 22    // P1.22
#define COL3 23    // P1.23

/* End of header guard. */
#endif /* KPM_DEFINES_H */
